"""Regenerate the shipped ASCII glyph atlas with Pillow and DejaVu fonts."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import sys

out = Path(__file__).resolve().parent
fonts = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("/usr/share/fonts/truetype/dejavu")
specs = [("SMALL", "Sans-Bold", 10, 13, 12), ("BODY", "Sans", 12, 15, 16),
         ("TITLE", "Sans-Bold", 16, 20, 20), ("CODE", "SansMono", 12, 15, 8)]
data = bytearray()
table = []
ranges = [(0x00a0, 0x017f), (0x0370, 0x03ff), (0x2000, 0x206f), (0x2070, 0x209f),
          (0x20a0, 0x20bf), (0x2100, 0x214f), (0x2190, 0x22ff), (0x2300, 0x232f),
          (0x25a0, 0x25ff)]
for name, face, size, height, width in specs:
    f = ImageFont.truetype(str(fonts / ("DejaVu" + face + ".ttf")), size, layout_engine=ImageFont.Layout.BASIC)
    table.append((len(data), width // 4, height))
    codes = list(range(32, 127))
    if name == "CODE":
        for lo, hi in ranges:
            codes.extend(range(lo, hi + 1))
    for char in map(chr, codes):
        im = Image.new("L", (width, height))
        ImageDraw.Draw(im).text((0, 0), char, fill=255, font=f)
        data.append(7 if name == "CODE" else max(2, round(f.getlength(char))))
        for y in range(height):
            for x in range(0, width, 4):
                data.append(sum(((im.getpixel((x+i, y))*3+127)//255) << (2*i) for i in range(4)))
(out / "font.bin").write_bytes(data)
(out / "font_layout.h").write_text("/* Generated by make_font.py */\n" +
    "static const Font fonts[] = {\n" +
    "".join("    {%d, %d, %d},\n" % row for row in table) + "};\n")
with (out / "font_layout.h").open("a") as header:
    header.write("static const unsigned code_ranges[][2] = {\n")
    for lo, hi in ranges:
        header.write(f"    {{0x{lo:x}, 0x{hi:x}}},\n")
    header.write("};\n")
