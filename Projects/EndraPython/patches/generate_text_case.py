"""Regenerate the case mappings with CPython and Unicode 15.0.0."""
from pathlib import Path
import unicodedata


def runs(values):
    """Coalesce consecutive code points with the same value."""
    values = iter(values)
    start, value = next(values)
    end = start
    for point, next_value in values:
        if point == end + 1 and next_value == value:
            end = point
        else:
            yield start, end, value
            start = end = point
            value = next_value
    yield start, end, value


def write_ranges(out, name, points):
    out.write(f"static const EpCaseRange {name}[] = {{\n")
    for start, end, delta in runs(points):
        out.write(f"    {{0x{start:X}, 0x{end:X}, {delta}}},\n")
    out.write("};\n\n")


def main():
    if unicodedata.unidata_version != "15.0.0":
        raise SystemExit("Run with Unicode 15.0.0 (CPython 3.12)")
    cased = []
    ignorable = []
    mappings = {"title": [], "lower": []}
    expansions = {"title": [], "lower": []}
    for point in range(0x110000):
        char = chr(point)
        is_cased = char.isupper() or char.islower() or char.istitle()
        if is_cased:
            cased.append((point, 0))
            ignores_case = ("AΣ" + char).lower()[1] == "ς"
        else:
            ignores_case = ("AΣ" + char + "A").lower()[1] == "σ"
        if ignores_case:
            ignorable.append((point, 0))
        for case, mapping in (("title", char.title()), ("lower", char.lower())):
            if char == mapping:
                continue
            if len(mapping) == 1:
                mappings[case].append((point, ord(mapping) - point))
            else:
                assert len(mapping) <= 3 and "\0" not in mapping
                expansions[case].append((point, [ord(c) for c in mapping]))
    with Path(__file__).with_name("text_case_data.h").open("w", encoding="ascii") as out:
        out.write("/* Generated by generate_text_case.py from Unicode 15.0.0. */\n\n")
        write_ranges(out, "ep_cased", cased)
        write_ranges(out, "ep_case_ignorable", ignorable)
        for i, case in enumerate(mappings):
            write_ranges(out, f"ep_{case}_ranges", mappings[case])
            out.write(f"static const EpCaseExpansion ep_{case}_expansions[] = {{\n")
            for point, mapped in expansions[case]:
                values = ", ".join(f"0x{value:X}" for value in mapped)
                out.write(f"    {{0x{point:X}, {{{values}}}}},\n")
            out.write("};\n")
            if i + 1 < len(mappings):
                out.write("\n")


if __name__ == "__main__":
    main()
